test_that("long reshaping preserves values, metadata and missing cells", {
  tab <- data.frame(ID = c("a", "b"), Estimate = c(1, NA), SE = c(.2, .3), Status = c("ok", "review"))
  p <- new_mfrm_plot_data("custom", list(table = tab))
  expect_identical(plot_data(p, "table"), tab)
  long <- plot_data(p, "table", format = "long", value_cols = c("Estimate", "SE"))
  expect_equal(long$Value, c(1, .2, NA, .3))
  expect_equal(long$ID, c("a", "a", "b", "b"))
  expect_equal(long$SourceRow, c(1L, 1L, 2L, 2L))
  expect_equal(long$Status, rep(tab$Status, each = 2))
  expect_error(plot_data(p, "table", format = "long"), "explicit")
  expect_error(plot_data(p, format = "long"), "Select")
  mat <- matrix(c(1, NA, 3, 4), 2, dimnames = list(c("same", "same"), c("X", "Y")))
  q <- new_mfrm_plot_data("custom", list(matrix = mat))
  long <- plot_data(q, "matrix", format = "long")
  expect_equal(long$Value, c(1, NA, 3, 4))
  expect_equal(long$Row, c(1, 2, 1, 2))
  expect_equal(long$RowLabel, rep("same", 4))
  expect_equal(long$ColumnLabel, c("X", "X", "Y", "Y"))
})

test_that("profile observations retain original units and omitted entities", {
  d <- data.frame(Rater = paste0("R", 1:6), Years = c(1, 2, 3, 11, 13, 14),
    Hours = c(3, NA, 4, 30, 40, 50))
  f <- mfrm_features(d, "Rater", c("Years", "Hours"))
  g <- mfrm_cluster_kmeans(f, 2, missing = "omit", silhouette = FALSE)
  p <- plot(g, type = "profile", feature = "Years", draw = FALSE)
  raw <- plot_data(p, "observations")
  expect_equal(raw$ID, d$Rater)
  expect_equal(raw$Value, d$Years)
  expect_false(raw$Included[2])
  expect_true(is.na(raw$Cluster[2]))
  expect_true(all(is.na(raw$MissingReason)))
  raw_hours <- plot_data(g, "observations", type = "profile", feature = "Hours")
  expect_true(is.na(raw_hours$Value[2]))
  expect_equal(raw_hours$MissingReason[2], "Not supplied")
  path <- tempfile(fileext = ".csv")
  on.exit(unlink(path), add = TRUE)
  utils::write.csv(raw_hours, path, row.names = FALSE)
  expect_equal(utils::read.csv(path)$Value, d$Hours)
})
